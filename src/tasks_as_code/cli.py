console = Console()
# Errors quote file paths and task ids. Rich's word wrap folds a long path across
# lines, inserting a break inside the token, which makes it uncopyable — so let
# the terminal wrap error output instead of rewriting it.
err_console = Console(stderr=True, soft_wrap=True)

STATUS_COLOURS = {
    "in_progress": "yellow",
    "todo": "white",
    "blocked": "red",
    "done": "green",
}


def _emit(payload: Any) -> None:
    """Write machine-readable output to stdout with nothing else mixed in."""
    print(json.dumps(payload, indent=2, ensure_ascii=False, sort_keys=True))


def _fail(message: str, as_json: bool = False) -> NoReturn:
    if as_json:
        print(json.dumps({"error": message}, indent=2, ensure_ascii=False))
    else:
        err_console.print(f"[red]{message}[/red]")
    raise typer.Exit(1)


def _paths(as_json: bool = False) -> Paths:
    try:
        return Paths.discover()
    except ProjectNotFound as exc:
        _fail(str(exc), as_json)


def _load(paths: Paths, as_json: bool = False, active_only: bool = False) -> list[TaskRef]:
    try:
        return load_active(paths) if active_only else load_all(paths)
    except TaskFileError as exc:
        _fail(f"Invalid task file: {exc}", as_json)


def _ensure_index_ignored(paths: Paths) -> bool:
    """Add the index to ``.gitignore``, returning whether the file was changed.

    ``INDEX.md`` is regenerated by every ``new``, ``mark`` and ``done``. Tracking
    it means two agents on separate branches conflict in almost every pull
    request, over a file that is derived from the YAML anyway. So it is generated
    locally and in CI instead of being committed.
    """
    pattern = paths.relative(paths.index_md)
    gitignore = paths.root / ".gitignore"
    existing = gitignore.read_text(encoding="utf-8") if gitignore.is_file() else ""
    if pattern in existing.split():
        return False
    prefix = "" if not existing or existing.endswith("\n") else "\n"
    note = "# Generated by 'tasc reindex' — regenerate it, do not track it.\n"
    gitignore.write_text(f"{existing}{prefix}{note}{pattern}\n", encoding="utf-8")
    return True


def _version_callback(value: bool) -> None:
    # Must run while parameters are parsed: by the time the group callback body
    # would run, Click has already rejected the missing subcommand.
    if value:
        print(__version__)
        raise typer.Exit()


