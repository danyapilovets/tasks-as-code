@app.command("validate")
def cmd_validate(
    as_json: bool = typer.Option(False, "--json", help="Machine-readable output."),
) -> None:
    """Check every file against the schema and report structural problems.

    Exits non-zero on any problem, so it works as a pre-commit hook or CI gate.
    """
    paths = _paths(as_json)
    try:
        refs = load_all(paths)
    except TaskFileError as exc:
        _fail(f"Invalid task file: {exc}", as_json)

    problems: list[str] = []

    seen: dict[str, int] = {}
    for ref in refs:
        seen[ref.task.id] = seen.get(ref.task.id, 0) + 1
    problems += [f"duplicate id: {task_id}" for task_id, n in sorted(seen.items()) if n > 1]

    known = set(seen)
    for ref in refs:
        problems += [
            f"{ref.task.id} depends on unknown task: {dep}"
            for dep in ref.task.depends_on
            if dep not in known
        ]
        if ref.task.id in ref.task.depends_on:
            problems.append(f"{ref.task.id} depends on itself")

    if as_json:
        _emit({"ok": not problems, "tasks": len(refs), "problems": problems})
        raise typer.Exit(1 if problems else 0)

    if problems:
        err_console.print(f"[red]{len(problems)} problem(s):[/red]")
        for problem in problems:
            err_console.print(f"  - {problem}")
        raise typer.Exit(1)
    console.print(f"[green]OK[/green] — {len(refs)} tasks valid")


#: Delegates rather than reimplements the rule, so upgrading tasc upgrades the
#: hook. Missing tasc is a warning, not a failure: a teammate without the tool
#: installed should not be unable to commit.
_COMMIT_MSG_HOOK = """#!/bin/sh
# Installed by 'tasc install-hook'. Remove this file to stop the check.
if command -v tasc >/dev/null 2>&1; then
    exec tasc check-ref --file "$1"
fi
echo "tasc not found; skipping the task reference check." >&2
"""

#: Runs before the editor opens, so the author sees the stamped subject and can
#: still change it. Merges and squashes are left alone: their messages are git's,
#: and the check exempts them anyway.
_PREPARE_COMMIT_MSG_HOOK = """#!/bin/sh
# Installed by 'tasc install-hook'. Remove this file to stop filling in issue keys.
case "$2" in
    merge|squash) exit 0 ;;
esac
if command -v tasc >/dev/null 2>&1; then
    exec tasc stamp "$1"
fi
"""


def _git_hooks_dir(root: Path) -> Path | None:
    """Locate the hooks directory, following the gitfile a worktree leaves behind."""
    git = root / ".git"
    if git.is_dir():
        return git / "hooks"
    if git.is_file():
        # Worktrees and submodules store "gitdir: <path>" instead of a directory.
        for line in git.read_text(encoding="utf-8").splitlines():
            if line.startswith("gitdir:"):
                target = Path(line.partition(":")[2].strip())
                resolved = target if target.is_absolute() else (root / target).resolve()
                return resolved / "hooks"
    return None


@app.command("install-hook")
def cmd_install_hook(
    force: bool = typer.Option(False, "--force", help="Overwrite existing hooks of these types."),
) -> None:
    """Install the commit-msg and prepare-commit-msg hooks.

    For repositories not using pre-commit. Git hooks are per-clone and cannot be
    committed, so this is what each person runs once; CI is what actually
    enforces the rule for everyone.
    """
    paths = _paths()
    hooks = _git_hooks_dir(paths.root)
    if hooks is None:
        _fail(f"No git repository found at {paths.root}")

    wanted = {"commit-msg": _COMMIT_MSG_HOOK, "prepare-commit-msg": _PREPARE_COMMIT_MSG_HOOK}
    present = [name for name in wanted if (hooks / name).exists()]
    if present and not force:
        _fail(f"{', '.join(present)} already exist(s) in {hooks}. Pass --force to replace.")

    hooks.mkdir(parents=True, exist_ok=True)
    for name, body in wanted.items():
        hook = hooks / name
        hook.write_text(body, encoding="utf-8")
        # On POSIX this is what makes git run the file rather than ignore it.
        # Windows has no execute bit, so the call only clears the read-only flag.
        hook.chmod(0o755)
        console.print(f"[green]Installed[/green] {hook}")
    console.print(
        "Commits must now name a task, and carry its issue key where it has one. "
        "Bypass a single commit with --no-verify."
    )


@app.command("stamp")
def cmd_stamp(
    file: Path = typer.Argument(
        ..., help="File holding the message, as prepare-commit-msg hooks pass it."
    ),
) -> None:
    """Write the task's issue key into a commit message.

    Meant as a prepare-commit-msg hook: the author writes the message they would
    write anyway, and the key that links the commit to its issue is filled in from
    the backlog. Always exits zero — a message that could not be stamped is for
    ``check-ref`` to accept or refuse, and failing here would only block the commit
    before the author sees why.
    """
    from .core.messages import stamp_message

    try:
        text = file.read_text(encoding="utf-8")
    except OSError as exc:
        err_console.print(f"[yellow]Could not read {file}: {exc}[/yellow]")
        return

    paths = _paths()
    result = stamp_message(
        text,
        _load(paths),
        subject_format=paths.config.refs.subject_format,
        skip_markers=paths.config.refs.skip_markers,
    )
    if result.changed:
        file.write_text(result.text, encoding="utf-8")
        console.print(f"[green]Stamped[/green] {result.key} onto the message")
        return
    if result.reason:
        console.print(f"[yellow]Left as written[/yellow] — {escape(result.reason)}")


@app.command("check-ref")
def cmd_check_ref(
    text: str | None = typer.Argument(None, help="Text to check. Omit to read stdin."),
    file: Path | None = typer.Option(
        None, "--file", "-f", help="Read the text from a file, as commit-msg hooks pass it."
    ),
    require_status: list[str] = typer.Option(
        [], "--require-status", help="Demand one of these statuses. Repeatable."
    ),
    as_json: bool = typer.Option(False, "--json", help="Machine-readable output."),
) -> None:
    """Check that a commit message, PR title or branch name names a real task.

    A regex in a hook can already demand that some id is present. This checks the
    id against the backlog, which is the part that catches an agent citing a task
    it invented. Exits non-zero on failure, so it works as a commit-msg hook and
    as a required status check.
    """
    if file is not None:
        try:
            text = file.read_text(encoding="utf-8")
        except OSError as exc:
            _fail(f"Could not read {file}: {exc}", as_json)
    elif text is None:
        text = sys.stdin.read()

    paths = _paths(as_json)
    refs = _load(paths, as_json)
    settings = paths.config.refs
    result = check_text(
        text,
        refs,
        skip_markers=settings.skip_markers,
        require_status=require_status or settings.require_status,
    )

    if as_json:
        _emit(result.to_dict())
        raise typer.Exit(0 if result.ok else 1)

    if result.skipped:
        # Markers are bracketed by convention, which is also Rich's markup syntax:
        # printed unescaped, "[skip-task]" renders as nothing at all.
        console.print(f"[yellow]Skipped[/yellow] — {escape(result.skipped)}")
        return
    if result.ok:
        console.print(f"[green]OK[/green] — references {', '.join(result.referenced)}")
        return

    err_console.print("[red]No valid task reference:[/red]")
    for problem in result.problems():
        err_console.print(f"  - {escape(problem)}")
    marker = settings.skip_markers[0] if settings.skip_markers else "[skip-task]"
    err_console.print(
        f"\nRun [bold]tasc next[/bold] to see what to work on, or add {escape(marker)} to bypass."
    )
    raise typer.Exit(1)


@app.command("stale")
def cmd_stale(
    days: int | None = typer.Option(None, "--days", help="Override the configured threshold."),
    as_json: bool = typer.Option(False, "--json", help="Machine-readable output."),
) -> None:
    """Report tasks stuck in progress, including any with no ``updated`` date.

    Exits non-zero when something is stale, so CI can catch abandoned work.
    """
    paths = _paths(as_json)
    refs = _load(paths, as_json)
    threshold = days if days is not None else paths.config.stale_after_days
    stale = stale_in_progress(refs, days=threshold)

    if as_json:
        _emit(
            {
                "threshold_days": threshold,
                "count": len(stale),
                "stale": [ref.to_dict(paths) for ref in stale],
            }
        )
        raise typer.Exit(1 if stale else 0)

    if not stale:
        console.print(f"[green]OK[/green] — nothing in progress longer than {threshold} days")
        return
    err_console.print(f"[yellow]{len(stale)} stale task(s) (threshold {threshold} days):[/yellow]")
    for ref in stale:
        who = f", owner: {ref.task.owner}" if ref.task.owner else ""
        err_console.print(
            f"  - {ref.task.id} (updated: {ref.task.updated or 'never'}{who}) — {ref.task.summary}"
        )
    raise typer.Exit(1)


@app.command("sync")
def cmd_sync(
    dry_run: bool = typer.Option(False, "--dry-run", help="Show what would change, send nothing."),
    check: bool = typer.Option(
        False, "--check", help="Compare the backlog against the project, then stop."
    ),
    active_only: bool = typer.Option(
        True,
        "--active-only/--all",
        help="Create issues for active tasks only. Archived tasks are still updated "
        "where an issue exists; --all creates issues for them too.",
    ),
) -> None:
    """Push tasks to Jira Cloud. Local YAML stays the source of truth."""
    from .integrations.jira import (
        JiraClient,
        JiraCredentials,
        JiraNotConfigured,
        ensure_epics,
        epic_label,
        preflight,
        sync_task,
        task_label,
    )

    paths = _paths()
    settings = paths.config.jira
    refs = _load(paths, active_only=False)
    if not refs:
        console.print("[yellow]No tasks to sync.[/yellow]")
        return

    try:
        credentials = JiraCredentials.from_env()
        client = JiraClient(credentials)
    except JiraNotConfigured as exc:
        _fail(str(exc))

    if check:
        candidates = [ref for ref in refs if ref.location == "active"] if active_only else refs
        console.print(
            f"Checking {len(candidates)} task(s) against {credentials.project_key} "
            f"on {credentials.base_url}"
        )
        findings = preflight(client, settings, candidates)
        if not findings:
            console.print("[green]OK[/green] — types, priorities, statuses and fields all line up")
            return
        for finding in findings:
            label = "[red]blocker[/red]" if finding.blocking else "[yellow]note[/yellow]"
            console.print(f"{label} {finding.message}")
        if any(finding.blocking for finding in findings):
            raise typer.Exit(1)
        return

    # One search for the whole backlog rather than one per task. A failure here is
    # not fatal: sync_task falls back to searching per task when handed no map.
    known: dict[str, dict] | None
    labels = [task_label(settings, ref.task.id) for ref in refs]
    if settings.epic_as_parent:
        labels += sorted({epic_label(settings, ref.epic) for ref in refs})
    try:
        known = client.issues_by_labels(labels)
    except Exception as exc:
        err_console.print(f"[yellow]Batched lookup failed ({exc}); searching per task.[/yellow]")
        known = None

    if active_only:
        # A closed task whose issue exists is still synced: its issue would
        # otherwise sit in the old status forever, saying work is in progress that
        # finished weeks ago. Without the map, telling which archived tasks have
        # an issue would cost a search each, so they wait for the next run.
        if known is None:
            err_console.print("[yellow]Archived tasks are skipped without the map.[/yellow]")
            refs = [ref for ref in refs if ref.location == "active"]
        else:
            refs = [
                ref
                for ref in refs
                if ref.location == "active" or task_label(settings, ref.task.id) in known
            ]

    console.print(f"Syncing {len(refs)} task(s) to {credentials.base_url}")
    if dry_run:
        console.print("[yellow]Dry run — nothing is sent.[/yellow]")

    # Before the tasks, so that two tasks of one epic cannot each create it. A
    # failure here costs the parents, not the sync.
    try:
        epics = ensure_epics(client, settings, refs, known=known, dry_run=dry_run)
    except Exception as exc:
        err_console.print(f"[yellow]Epics unavailable ({exc}); syncing without parents.[/yellow]")
        epics = {}

    table = Table(show_header=True, header_style="bold")
    table.add_column("ID")
    table.add_column("Result")
    failures = 0
    recorded = 0
    for ref in refs:
        try:
            outcome = sync_task(
                client,
                settings,
                ref,
                dry_run=dry_run,
                known=known,
                create=not active_only or ref.location == "active",
                parent=epics.get(ref.epic),
            )
            table.add_row(ref.task.id, outcome)
        except Exception as exc:
            failures += 1
            table.add_row(ref.task.id, f"[red]{exc}[/red]")
            continue
        key = getattr(outcome, "key", None)
        if key and not dry_run and record_jira_key(paths, ref.task.id, key):
            recorded += 1
    console.print(table)
    if recorded:
        console.print(f"Wrote {recorded} issue key(s) into task files — commit them.")
    if failures:
        err_console.print(f"[red]{failures} task(s) failed to sync.[/red]")
        raise typer.Exit(1)


if __name__ == "__main__":  # pragma: no cover - exercised via the console script
    sys.exit(app())
